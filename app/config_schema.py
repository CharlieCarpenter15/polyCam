"""Single source of truth for every configuration option.

Everything else is generated from this file:

* defaults for a brand-new appliance
* type coercion + validation when a value arrives from YAML, the environment
  or the Settings web page
* the Settings web page itself (groups, labels, help text, widgets)
* ``config/config.example.yaml`` and the options table in the README
  (both regenerated by ``scripts/gen-config-docs.py``)

Adding a new option means adding one ``Field`` below. No other file needs to
change, which is what keeps the appliance easy to maintain.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Callable, Iterable

# ---------------------------------------------------------------------------
# Field definition
# ---------------------------------------------------------------------------

#: Widget/coercion types understood by the config loader and the Settings UI.
TYPES = ("str", "text", "int", "float", "bool", "choice", "list", "password")


@dataclass(frozen=True)
class Field:
    """One configuration option."""

    key: str
    type: str
    default: Any
    group: str
    label: str
    help: str = ""
    choices: tuple[str, ...] = ()
    #: Inclusive bounds for numeric fields.
    minimum: float | None = None
    maximum: float | None = None
    #: Secrets are redacted in logs and in ``GET /api/settings``.
    secret: bool = False
    #: Hidden behind "Advanced" in the Settings UI.
    advanced: bool = False
    #: systemd units that must be restarted for a change to take effect.
    restart_units: tuple[str, ...] = ()
    #: Optional extra validator: return None if OK, or an error string.
    validator: Callable[[Any], str | None] | None = None
    #: Placeholder shown in the Settings UI when empty.
    placeholder: str = ""

    def __post_init__(self) -> None:  # pragma: no cover - developer guard
        if self.type not in TYPES:
            raise ValueError(f"{self.key}: unknown field type {self.type!r}")


# ---------------------------------------------------------------------------
# Validators
# ---------------------------------------------------------------------------


def _validate_url_or_empty(value: Any) -> str | None:
    text = str(value or "").strip()
    if not text:
        return None
    lowered = text.lower()
    ok_prefixes = ("http://", "https://", "webcal://", "file://", "/")
    if not lowered.startswith(ok_prefixes):
        return "Must start with https://, http://, webcal://, file:// or / (a local path)."
    return None


def _validate_timezone(value: Any) -> str | None:
    text = str(value or "").strip()
    if not text:
        return None
    try:
        from zoneinfo import ZoneInfo

        ZoneInfo(text)
    except Exception:
        return "Unknown time zone. Use an IANA name such as Europe/London or Asia/Singapore."
    return None


def _validate_host(value: Any) -> str | None:
    text = str(value or "").strip()
    if not text:
        return "Cannot be empty. Use 127.0.0.1 to keep the dashboard private."
    return None


def _validate_pin(value: Any) -> str | None:
    text = str(value or "").strip()
    if not text:
        return None
    if not text.isdigit():
        return "The admin PIN must be digits only (it is typed on a TV remote)."
    if len(text) < 4:
        return "Use at least 4 digits."
    return None



FIELDS_BY_KEY: dict[str, Field] = {f.key: f for f in FIELDS}

#: Keys whose values must never be written to a log line or a JSON API response.
SECRET_KEYS: frozenset[str] = frozenset(f.key for f in FIELDS if f.secret)


def defaults() -> dict[str, Any]:
    """A fresh, fully-populated configuration dictionary."""
    out: dict[str, Any] = {}
    for f in FIELDS:
        out[f.key] = list(f.default) if isinstance(f.default, list) else f.default
    return out


def grouped_fields(include_advanced: bool = True) -> list[tuple[str, str, str, list[Field]]]:
    """Fields arranged for the Settings UI: ``(id, title, help, fields)``."""
    out = []
    for gid, title in GROUPS:
        members = [
            f for f in FIELDS if f.group == gid and (include_advanced or not f.advanced)
        ]
        if members:
            out.append((gid, title, GROUP_HELP.get(gid, ""), members))
    return out


def restart_units_for(keys: Iterable[str]) -> list[str]:
    """systemd units that need restarting after ``keys`` changed."""
    units: list[str] = []
    for key in keys:
        f = FIELDS_BY_KEY.get(key)
        if not f:
            continue
        for unit in f.restart_units:
            if unit not in units:
                units.append(unit)
    return units
